#!/usr/bin/env bash
# Writes the entitlements for the container app and the packet tunnel extension so both carry the
# SAME App Group and the Network Extension packet-tunnel-provider key, then verifies that
# project.yml and Shared/AppGroup.swift agree with them.
#
# iOS only creates a shared container when the app and the appex are signed with an identical
# com.apple.security.application-groups value. When it is missing from one side (or both, as the
# TrollStore IPA shipped until now) nehelper kills the extension right after launch and the app
# shows "The VPN session failed because an internal error occurred".
#
# Written files:
#   SL_Proxy/SL_Proxy.entitlements              app    - CODE_SIGN_ENTITLEMENTS in project.yml
#   SL_ProxyTunnel/SL_ProxyTunnel.entitlements  appex  - CODE_SIGN_ENTITLEMENTS in project.yml
#   Signing/MainApp.entitlements                app    - superset used by package-unsigned-ipa.sh
#   Signing/PacketTunnel.entitlements           appex  - for the ad-hoc signed TrollStore IPA
#
# Usage:
#   scripts/setup-app-group.sh          write the files, patch AppGroup.swift, verify
#   scripts/setup-app-group.sh --check  verify only
#
# Environment:
#   APP_GROUP_ID   App Group identifier                 (default group.sailorsloot.proxy)
#   TEAM_PREFIX    fake team prefix for the TrollStore application-identifier (default SLPROXY000)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP_GROUP_ID="${APP_GROUP_ID:-group.sailorsloot.proxy}"
TEAM_PREFIX="${TEAM_PREFIX:-SLPROXY000}"
APP_BUNDLE_ID="com.slproxy.app"
TUNNEL_BUNDLE_ID="com.slproxy.app.tunnel"

APP_ENT="$ROOT/SL_Proxy/SL_Proxy.entitlements"
TUNNEL_ENT="$ROOT/SL_ProxyTunnel/SL_ProxyTunnel.entitlements"
TS_APP_ENT="$ROOT/Signing/MainApp.entitlements"
TS_TUNNEL_ENT="$ROOT/Signing/PacketTunnel.entitlements"
PROJECT_YML="$ROOT/project.yml"
APP_GROUP_SWIFT="$ROOT/Shared/AppGroup.swift"

MODE="write"
[ "${1:-}" = "--check" ] && MODE="check"

case "$APP_GROUP_ID" in
  group.*) ;;
  *) echo "error: APP_GROUP_ID must start with 'group.' (got '$APP_GROUP_ID')"; exit 1 ;;
esac

# ---------------------------------------------------------------------------------------------
# Writers
# ---------------------------------------------------------------------------------------------
plist_header() {
  cat <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
EOF
}

plist_footer() {
  cat <<'EOF'
</dict>
</plist>
EOF
}

# Entitlements Xcode signs with. Capability keys only: Xcode injects application-identifier,
# team-identifier and get-task-allow from the provisioning profile itself.
write_xcode_entitlements() {
  local path="$1" label="$2"
  {
    plist_header
    cat <<EOF
    <!-- $label. Generated by scripts/setup-app-group.sh; change APP_GROUP_ID there, not here. -->
    <key>com.apple.developer.networking.networkextension</key>
    <array>
        <string>packet-tunnel-provider</string>
    </array>
    <key>com.apple.security.application-groups</key>
    <array>
        <string>$APP_GROUP_ID</string>
    </array>
EOF
    plist_footer
  } > "$path"
}

# Entitlements for the ad-hoc signed TrollStore IPA. TrollStore keeps whatever the signature
# carries but synthesizes nothing, so the identifiers are spelled out explicitly.
write_trollstore_entitlements() {
  local path="$1" label="$2" bundle_id="$3" with_vpn_api="$4"
  {
    plist_header
    cat <<EOF
    <!-- $label for the TrollStore IPA (scripts/package-unsigned-ipa.sh).
         Generated by scripts/setup-app-group.sh; change APP_GROUP_ID / TEAM_PREFIX there, not here. -->

    <!-- Network Extension: packet tunnel + app proxy providers -->
    <key>com.apple.developer.networking.networkextension</key>
    <array>
        <string>packet-tunnel-provider</string>
        <string>app-proxy-provider</string>
    </array>
EOF
    if [ "$with_vpn_api" = "1" ]; then
      cat <<'EOF'

    <!-- Personal VPN API (lets NETunnelProviderManager write configurations) -->
    <key>com.apple.developer.networking.vpn.api</key>
    <array>
        <string>allow-vpn</string>
    </array>
EOF
    fi
    cat <<EOF

    <!-- Shared container. Must be identical in the app and the extension or containermanagerd
         refuses to hand out the group container and nehelper tears the tunnel down at launch. -->
    <key>com.apple.security.application-groups</key>
    <array>
        <string>$APP_GROUP_ID</string>
    </array>

    <!-- Shared managed-VPN keychain group. -->
    <key>keychain-access-groups</key>
    <array>
        <string>com.apple.managed.vpn.shared</string>
    </array>

    <!-- The prefix must match between the app and the extension. -->
    <key>application-identifier</key>
    <string>$TEAM_PREFIX.$bundle_id</string>
    <key>com.apple.developer.team-identifier</key>
    <string>$TEAM_PREFIX</string>
    <key>get-task-allow</key>
    <false/>
EOF
    plist_footer
  } > "$path"
}

# Keeps the identifier the Swift code looks up in step with the entitlements.
patch_app_group_swift() {
  local tmp
  tmp="$(mktemp)"
  sed -E "s|(static let defaultIdentifier = \")[^\"]*(\")|\\1$APP_GROUP_ID\\2|" "$APP_GROUP_SWIFT" > "$tmp"
  mv "$tmp" "$APP_GROUP_SWIFT"
}

# ---------------------------------------------------------------------------------------------
# Verification
# ---------------------------------------------------------------------------------------------
PLISTBUDDY=/usr/libexec/PlistBuddy

read_group() {
  if [ -x "$PLISTBUDDY" ]; then
    "$PLISTBUDDY" -c "Print :com.apple.security.application-groups:0" "$1" 2>/dev/null || true
  else
    # Non-macOS fallback: first <string> inside the application-groups array.
    sed -n '/com.apple.security.application-groups/,/<\/array>/p' "$1" \
      | sed -n 's/.*<string>\(.*\)<\/string>.*/\1/p' | head -n 1
  fi
}

has_packet_tunnel() {
  if [ -x "$PLISTBUDDY" ]; then
    "$PLISTBUDDY" -c "Print :com.apple.developer.networking.networkextension" "$1" 2>/dev/null \
      | grep -q "packet-tunnel-provider"
  else
    sed -n '/com.apple.developer.networking.networkextension/,/<\/array>/p' "$1" \
      | grep -q "packet-tunnel-provider"
  fi
}

verify() {
  local status=0 f group
  for f in "$APP_ENT" "$TUNNEL_ENT" "$TS_APP_ENT" "$TS_TUNNEL_ENT"; do
    if [ ! -f "$f" ]; then
      echo "error: missing ${f#"$ROOT"/}"; status=1; continue
    fi
    if command -v plutil >/dev/null 2>&1 && ! plutil -lint -s "$f" >/dev/null; then
      echo "error: ${f#"$ROOT"/} is not a valid plist"; status=1
    fi
    if ! has_packet_tunnel "$f"; then
      echo "error: packet-tunnel-provider missing from ${f#"$ROOT"/}"; status=1
    fi
    group="$(read_group "$f")"
    if [ "$group" != "$APP_GROUP_ID" ]; then
      echo "error: ${f#"$ROOT"/} has App Group '${group:-<none>}', expected '$APP_GROUP_ID'"; status=1
    fi
  done

  for f in "SL_Proxy/SL_Proxy.entitlements" "SL_ProxyTunnel/SL_ProxyTunnel.entitlements"; do
    if ! grep -q "CODE_SIGN_ENTITLEMENTS: $f" "$PROJECT_YML"; then
      echo "error: project.yml does not point a target at $f (CODE_SIGN_ENTITLEMENTS)"; status=1
    fi
  done

  if ! grep -q "static let defaultIdentifier = \"$APP_GROUP_ID\"" "$APP_GROUP_SWIFT"; then
    echo "error: Shared/AppGroup.swift defaultIdentifier does not match '$APP_GROUP_ID'"; status=1
  fi

  if [ "$status" -eq 0 ]; then
    echo "App Group OK: '$APP_GROUP_ID' + packet-tunnel-provider in app and tunnel entitlements (Xcode + TrollStore)"
  fi
  return "$status"
}

# ---------------------------------------------------------------------------------------------
if [ "$MODE" = "write" ]; then
  write_xcode_entitlements "$APP_ENT" "Container app entitlements"
  write_xcode_entitlements "$TUNNEL_ENT" "Packet tunnel extension entitlements"
  write_trollstore_entitlements "$TS_APP_ENT" "Container app entitlements" "$APP_BUNDLE_ID" 1
  write_trollstore_entitlements "$TS_TUNNEL_ENT" "NEPacketTunnelProvider extension entitlements" "$TUNNEL_BUNDLE_ID" 0
  patch_app_group_swift
  echo "Wrote entitlements for App Group '$APP_GROUP_ID'"
fi

verify
